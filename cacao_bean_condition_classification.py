import pandas as pd
import numpy as np

def aplicar_filtro_y_normalizar(ruta_entrada, ruta_salida, ventana=5):
    df = pd.read_csv(ruta_entrada)
    print(f"Filas originales: {len(df)}")

    df_limpio = df.dropna()
    df_limpio = df_limpio.drop_duplicates(subset=['Time'], keep='first')

    tiempo = df_limpio['Time']
    columnas_sensores = [col for col in df_limpio.columns if col.startswith('Sensor_')]

    # 1. Aplicar filtro de ventana
    df_suavizado = df_limpio[columnas_sensores].rolling(window=ventana, min_periods=1).mean()

    # 2. Normalización Min-Max (Mapea el mínimo real a 0 y el máximo real a 1)
    df_min = df_suavizado.min()
    df_max = df_suavizado.max()

    # Fórmula: (Valor - Mínimo) / (Máximo - Mínimo)
    df_normalizado = (df_suavizado - df_min) / (df_max - df_min)

    if 'Archivo_Origen' in df_limpio.columns:
        df_normalizado['Archivo_Origen'] = df_limpio['Archivo_Origen']

    df_normalizado.insert(0, 'Time', tiempo)

    df_normalizado.to_csv(ruta_salida, index=False)

    print(f"Filas después del filtrado y normalización: {len(df_normalizado)}")
    print(f"Archivo final guardado en: {ruta_salida}")
    print("-" * 30)

    return df_normalizado

