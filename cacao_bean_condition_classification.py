def procesar_archivos_cacao(carpeta_origen, archivo_destino):
    rutas_archivos = glob.glob(os.path.join(carpeta_origen, '*.xlsx'))
    dataframes = []

    for archivo in rutas_archivos:
        try:
            df = pd.read_excel(archivo, engine='calamine')
            df.rename(columns={
                'Untitled': 'Sensor_1',
                'Untitled 1': 'Sensor_2',
                'Untitled 2': 'Sensor_3',
                'Untitled 3': 'Sensor_4',
                'Untitled 4': 'Sensor_5',
                'Untitled 5': 'Sensor_6'
            }, inplace=True)
            df['Archivo_Origen'] = os.path.basename(archivo)
            dataframes.append(df)
        except Exception as e:
            print(f"❌ Fallo crítico: {e}")
            try:
                df = pd.read_excel(archivo, engine='openpyxl')
                df.rename(columns={
                    'Untitled': 'Sensor_1',
                    'Untitled 1': 'Sensor_2',
                    'Untitled 2': 'Sensor_3',
                    'Untitled 3': 'Sensor_4',
                    'Untitled 4': 'Sensor_5',
                    'Untitled 5': 'Sensor_6'
                }, inplace=True)
                df['Archivo_Origen'] = os.path.basename(archivo)
                dataframes.append(df)
                print("✅ Cargado exitosamente con motor alternativo.")
            except Exception as e2:
                print(f"❌ Fallo crítico: {e2}")
                print("Sugerencia: Abre el Excel, 'Guardar como' y elige .CSV o quita los colores de las celdas.")

    if dataframes:
        df_unido = pd.concat(dataframes, ignore_index=True)
        df_unido.to_csv(archivo_destino, index=False)
        print(f"Archivos unidos con éxito. El resultado se guardó en: {archivo_destino}")
        print(f"Total de filas en el archivo unido: {len(df_unido)}")
    else:
        print("No se encontraron datos para procesar.")

